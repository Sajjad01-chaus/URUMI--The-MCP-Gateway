"""Generate deploy/secrets/<env>.secrets.yaml with random credentials for every chart.

Usage: python scripts/gen_secrets.py local|prod [--force]
The file is gitignored. Never regenerate it for a running environment: the databases keep the old passwords.
"""

import base64
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def password(n: int = 24) -> str:
    return secrets.token_urlsafe(n)


def main() -> None:
    if len(sys.argv) < 2 or sys.argv[1] not in ("local", "prod"):
        sys.exit("usage: python scripts/gen_secrets.py local|prod [--force]")
    env = sys.argv[1]
    out = ROOT / "deploy" / "secrets" / f"{env}.secrets.yaml"
    if out.exists() and "--force" not in sys.argv:
        sys.exit(f"{out} already exists; refusing to overwrite (databases keep the old passwords). Use --force for a fresh cluster only.")

    values = {
        "mysqlRootPassword": password(),
        "mysqlPassword": password(),
        "wpAdminUser": "admin",
        "wpAdminPassword": password(18),
        "wpAdminEmail": "admin@urumi.local",
        "wooConsumerKey": "ck_" + secrets.token_hex(20),
        "wooConsumerSecret": "cs_" + secrets.token_hex(20),
        "wooMcpToken": password(32),
        "postgresPassword": password(),
        "sessionSecret": password(32),
        "chatTokenSecret": password(32),
        "credentialEncryptionKey": base64.urlsafe_b64encode(secrets.token_bytes(32)).decode(),
        "bootstrapAdminEmail": "admin@urumi.local",
        "bootstrapAdminPassword": password(18),
        "notesMcpToken": password(32),
        "fxMcpApiKey": password(32),
        "groqApiKey": "REPLACE_WITH_YOUR_GROQ_KEY",
    }

    out.parent.mkdir(parents=True, exist_ok=True)
    lines = [f"# Generated by scripts/gen_secrets.py for '{env}'. DO NOT COMMIT.", "secrets:"]
    lines += [f'  {key}: "{value}"' for key, value in values.items()]
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
